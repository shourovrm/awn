#!/usr/bin/env python3
"""Write core/data/.../quran/QuarterData.kt: the 240 quarters (rub' al-hizb) of the Quran.

Source: Quran.com API v4, `rub_el_hizb_number` (1..240) on every verse of
/verses/by_chapter. The first verse of each quarter is the quarter start. Pages come from the
`ayah` table of awn-data/quran/quran.sqlite (V1 and V2 prints; they differ for a few ayahs).

The Kotlin file records the SHA-256 of the canonical text "quarter,surah,ayah,page_v1,page_v2"
(one line per quarter, in order, joined by newlines); a unit test recomputes it.

Usage: python3 tools/build_quarters.py
"""

import hashlib
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import quran_com

QUARTER_COUNT = 240
OUTPUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..",
    "core/data/src/main/kotlin/app/awn/quran/core/data/quran/QuarterData.kt",
)


def first_ayah_of_each_quarter():
    first = {}
    for verse in quran_com.all_chapter_verses("en"):
        quarter = verse["rub_el_hizb_number"]
        surah, ayah = quran_com.split_verse_key(verse)
        first.setdefault(quarter, (surah, ayah))
    if sorted(first) != list(range(1, QUARTER_COUNT + 1)):
        raise ValueError(f"expected quarters 1..{QUARTER_COUNT}, got {sorted(first)[:3]}..")
    return first


def main():
    firsts = first_ayah_of_each_quarter()
    database = sqlite3.connect(os.path.join(quran_com.DATA_ROOT, "quran", "quran.sqlite"))
    rows = []
    for quarter in range(1, QUARTER_COUNT + 1):
        surah, ayah = firsts[quarter]
        page_v1, page_v2 = database.execute(
            "SELECT page_v1, page_v2 FROM ayah WHERE surah = ? AND ayah = ?", (surah, ayah)
        ).fetchone()
        rows.append((quarter, surah, ayah, page_v1, page_v2))
    canonical = "\n".join(",".join(str(value) for value in row) for row in rows)
    checksum = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    retrieved = quran_com.retrieval_date(
        "/verses/by_chapter/1",
        words="true", word_fields=quran_com.WORD_FIELDS, fields="text_uthmani",
        translations=",".join(str(i) for i in quran_com.AYAH_TRANSLATION_IDS),
        word_translation_language="en", per_page=50, page=1,
    )
    lines = []
    for quarter, surah, ayah, page_v1, page_v2 in rows:
        lines.append(f'        "{surah}:{ayah}:{page_v1}:{page_v2}",')
    body = "\n".join(lines)
    text = f'''package app.awn.quran.core.data.quran

/**
 * Generated by tools/build_quarters.py; do not edit by hand.
 *
 * Source: Quran.com API v4 `rub_el_hizb_number` on /verses/by_chapter (retrieved {retrieved}); pages
 * from quran.sqlite. Each entry is "surah:ayah:pageV1:pageV2" of the first ayah of quarter 1..240.
 * SHA-256 of the canonical text (see the script): {checksum}
 */
internal object QuarterData {{
    const val SOURCE_SHA256 = "{checksum}"

    val rows: List<String> =
        listOf(
{body}
        )
}}
'''
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {len(rows)} quarters, sha256 {checksum}")


if __name__ == "__main__":
    main()
